const ignoredSelectors='#wiki-submit-status,#wiki-progress-label,#wiki-cover-message,#wiki-evidence-message,.wk-count-status,[data-wiki-lang]';
const translateText=(value,lang)=>{
 if(lang!=='en')return value;
 const trimmed=value.trim();
 if(!trimmed)return value;
 const exact=translations[trimmed];
 if(exact)return value.replace(trimmed,exact);
 const numberLabel=/^(电影|剧集|集数)（(不含多版本|包含多版本)）(?:（(必填|选填)）)?$/u.exec(trimmed);
 if(numberLabel)return value.replace(trimmed,translations[numberLabel[1]]+' ('+translations[numberLabel[2]]+')'+(numberLabel[3]?' ('+translations[numberLabel[3]]+')':''));
 return value;
};
