export function applyLanguage(root,lang){
 // Explicit values are essential: options with only textContent otherwise change
 // their form value when their visible language changes.
 root.querySelectorAll('select option').forEach(option=>{
  if(!option.hasAttribute('value'))option.setAttribute('value',option.value);
 });
 const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
 let node;
 while((node=walker.nextNode())){
  if(node.parentElement?.closest(ignoredSelectors))continue;
  if(!originalNodes.has(node))originalNodes.set(node,node.nodeValue);
  node.nodeValue=translateText(originalNodes.get(node),lang);
 }
 for(const element of root.querySelectorAll('[placeholder],[aria-label],[alt],[title]')){
  if(!originalAttributes.has(element)){
   const originals={};
   for(const attr of attributes)if(element.hasAttribute(attr))originals[attr]=element.getAttribute(attr);
   originalAttributes.set(element,originals);
  }
  const originals=originalAttributes.get(element);
  for(const [attr,value] of Object.entries(originals))element.setAttribute(attr,translateText(value,lang));
 }
 document.documentElement.lang=lang==='en'?'en':'zh-CN';
 document.title=lang==='en'?'Emby Wiki submission · LiangYou Tech':'Emby Wiki 自助投稿 · 良友科技';
 for(const button of root.querySelectorAll('[data-wiki-lang]')){
  const active=button.dataset.wikiLang===lang;
  button.setAttribute('aria-pressed',String(active));
  button.classList.toggle('is-active',active);
 }
}
