export function localizeNotice(message,lang){
 if(lang!=='en')return message;
 if(noticeMap[message])return noticeMap[message];
 if(message.startsWith('投稿成功，已进入待审核队列。')){
  const match=/投稿编号：([^\n]+)/.exec(message);
  return 'Submitted successfully and queued for review.\nSubmission ID: '+(match?match[1]:'—')+'\nThe profile will appear in Emby Wiki after approval.';
 }
 if(message.startsWith('封面已就绪，约 '))return message.replace('封面已就绪，约 ','Cover ready · about ');
 if(message.startsWith('统计凭证已就绪，约 '))return message.replace('统计凭证已就绪，约 ','Evidence ready · about ');
 if(message.endsWith('。草稿已保留，可使用原表单重试。')){
  return localizeNotice(message.slice(0,-'。草稿已保留，可使用原表单重试。'.length),'en')+'. Your draft has been saved; you can retry.';
 }
 if(message.includes('须为有效日期'))return 'Enter a valid date that is not in the future.';
 if(message.includes('须为 0–100000000 的整数'))return 'Counts must be whole numbers between 0 and 100,000,000.';
 if(message.includes('须填写')||message.includes('不能为空'))return 'Complete the required field and check its length.';
 if(message.includes('请选择'))return 'Check your selected option and try again.';
 if(message.includes('请使用公开的 HTTPS 地址')||message.includes('请填写完整的 HTTPS 链接'))return 'Enter a complete public HTTPS URL.';
 if(message.includes('不能超过'))return 'The entered text is too long.';
 return message;
}
